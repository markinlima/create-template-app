import path from "node:path";
import { fileURLToPath } from "node:url";

import * as p from "@clack/prompts";

import { scanDirectory } from "./utils/scan-directory";

console.clear();

// ? CONFIG
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const projectRoot = path.resolve(__dirname, "..");
const publicImagesDir = path.join(projectRoot, "public", "images");

const outputTypeFile = "src/types/images-types.generated.ts";
const imageTypeVariableName = "ImageTypes";

/**
 * Gera o arquivo de tipos das imagens disponíveis.
 */
async function generateImagesType(): Promise<void> {
	try {
		p.box("📸 Gerador de Tipos de Imagens", "", {
			contentAlign: "center",
			contentPadding: 2,
			rounded: true,
		});

		const scanDirSpinner = p.spinner();
		scanDirSpinner.start(`Escaneando diretório: ${publicImagesDir}`);
		const files = await scanDirectory({ dir: publicImagesDir, recursive: true });

		let types: string;

		if (files.length > 0) {
			scanDirSpinner.stop(`Arquivos encontrados: ${files.length}`);

			types = files.map((f) => `"${f.relativePath.workDir}"`).join(" | ");
		} else {
			scanDirSpinner.stop("⚠️  Nenhum arquivo encontrado. Gerando tipo como 'string'.");

			types = "string";
		}

		const typeContent = `
// This file is auto-generated by scripts/create-images-type.ts
// Do not edit manually!

export type ${imageTypeVariableName} = ${types};\n`;

		p.log.step("Gerando arquivo de tipos!");

		await Bun.write(outputTypeFile, typeContent, { createPath: true });

		p.log.success("✨ Tipos gerados com sucesso!");
		p.log.info(`Arquivo salvo em: ${outputTypeFile}`);

		process.exit(0);
	} catch (error) {
		p.log.error("❌ Erro ao gerar tipos de imagens:");
		console.error(error);

		process.exit(1);
	}
}

await generateImagesType();
